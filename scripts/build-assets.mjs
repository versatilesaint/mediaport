// Bundles apps/cloud/public/assets into the Worker as a generated module, so a deploy is a single script upload.
// Run automatically by `npm test` and `npm run deploy`. The output file is generated; don't edit it.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { join, relative, extname } from 'node:path';
import { createHash } from 'node:crypto';

const root = new URL('../apps/cloud/public/', import.meta.url).pathname;
const outFile = new URL('../apps/cloud/src/generated/assets.ts', import.meta.url).pathname;
const TYPES = { '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.woff2': 'font/woff2', '.txt': 'text/plain; charset=utf-8', '.svg': 'image/svg+xml' };

const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const entries = {};
let total = 0;
for (const file of walk(root)) {
  const type = TYPES[extname(file)];
  if (!type) continue;
  const buf = readFileSync(file);
  total += buf.length;
  const binary = !type.startsWith('text/') && type !== 'image/svg+xml';
  entries['/' + relative(root, file).split('\\').join('/')] = {
    type,
    b64: binary,
    body: binary ? buf.toString('base64') : buf.toString('utf8'),
    etag: '"' + createHash('sha256').update(buf).digest('base64url').slice(0, 22) + '"',
  };
}
mkdirSync(new URL('../apps/cloud/src/generated/', import.meta.url).pathname, { recursive: true });
writeFileSync(outFile, '// Generated by scripts/build-assets.mjs. Do not edit.\nexport const ASSETS: Record<string, { type: string; b64: boolean; body: string; etag: string }> = ' + JSON.stringify(entries) + ';\n');
console.log(`bundled ${Object.keys(entries).length} assets, ${(total / 1024).toFixed(0)} KB`);
